function getAllSeedRows() {
  const rows = [];
  for (const [key, perLocale] of Object.entries(MATRIX)) {
    for (const loc of I18N_LOCALES) {
      const val = perLocale[loc];
      if (val != null && val !== '') {
        rows.push({ locale: loc, key, value: val });
      }
    }
  }
  return rows;
}

function getAllKeys() {
  return Object.keys(MATRIX).sort();
}

function normalizeLocaleKey(locale) {
  const s = String(locale || '')
    .toLowerCase()
    .replace(/[^a-z]/g, '')
    .slice(0, 8);
  const loc = s || 'en';
  return I18N_LOCALES.includes(loc) ? loc : 'en';
}

/** Flat map of default strings for API + client; DB entries override per key. */
function getSeedStringsForLocale(locale) {
  const loc = normalizeLocaleKey(locale);
  const out = {};
  for (const [key, perLocale] of Object.entries(MATRIX)) {
    const raw = perLocale[loc] ?? perLocale.en;
    if (raw != null && String(raw).length) out[key] = String(raw);
  }
  return out;
}

